import { mkdir } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import type { DiscoveredApp, Endpoint, Repository } from "@forge/server";

type RepositoryOf<M> = { [K in keyof M]: M[K] extends Repository ? M[K] : never }[keyof M];

type RemoteCall<E> =
  E extends Endpoint<any, any, infer CallIn, any, infer Out, true>
    ? {} extends CallIn
      ? (input?: CallIn) => Promise<Out>
      : (input: CallIn) => Promise<Out>
    : never;

/** Browser-visible API of a repository module: only its `remote: true` functions. */
export type RemoteApi<M> = {
  [K in keyof RepositoryOf<M> as RepositoryOf<M>[K] extends { remote: true } ? K : never]: RemoteCall<RepositoryOf<M>[K]>;
};

/**
 * Writes `.forge/types.d.ts`: fills `forge:router` with one entry per app that
 * exposes remote functions. Regenerated at startup; not versioned.
 */
export async function writeTypes(root: string, apps: DiscoveredApp[]): Promise<string> {
  const dir = join(root, ".forge");
  await mkdir(dir, { recursive: true });
  const exposed = apps.filter((a) => a.remotes.length > 0);
  const rel = (file: string) => {
    const r = relative(dir, file).split(sep).join("/");
    return r.startsWith(".") ? r : `./${r}`;
  };
  const imports = exposed.map((a) => `import type * as app_${a.name} from ${JSON.stringify(rel(a.file))};`);
  const entries = exposed.map((a) => `    ${a.name}: RemoteApi<typeof app_${a.name}>;`);
  const file = join(dir, "types.d.ts");
  await Bun.write(
    file,
    `// Generated by Forge. Do not edit.
/// <reference types="forge/ambient" />
${exposed.length ? `import type { RemoteApi } from "forge/web";\n${imports.join("\n")}\n` : "export {};\n"}
declare module "forge:router" {
  interface Remote {
${entries.join("\n")}
  }
}
`,
  );
  return file;
}
