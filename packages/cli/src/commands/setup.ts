import { existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { loadConfig, type ResolvedConfig } from "@forge/core";
import type { Out } from "../util.ts";

/** Repository root when the project lives in a Bun workspace (e.g. the Forge monorepo). */
function workspaceRoot(root: string): string | null {
  let dir = dirname(root);
  while (dir !== dirname(dir)) {
    const pkg = join(dir, "package.json");
    if (existsSync(pkg) && (require(pkg) as { workspaces?: unknown }).workspaces) return dir;
    dir = dirname(dir);
  }
  return null;
}

const BUN_IMAGE = "oven/bun:1.4";
const RUNTIME_IMAGE = "gcr.io/distroless/base-debian12:nonroot";

function dockerfile(root: string, config: ResolvedConfig): string {
  const repo = workspaceRoot(root);
  const project = repo ? relative(repo, root).split("\\").join("/") : ".";
  const engine = repo && existsSync(join(repo, "packages/rust-engine/native/Cargo.toml"));
  const sqlite = config.db?.provider === "sqlite";
  const port = config.server.port ?? 3000;
  const lines: string[] = [
    "# Generated by `forge setup docker` (Dokploy, Railway, any Docker host).",
    repo ? "# Build context: the repository root (the project is a workspace member)." : "# Build context: this folder.",
    "",
  ];
  if (engine) {
    lines.push(
      "# Forge's native engine (Rust), embedded in the executable.",
      "FROM rust:1-slim AS engine",
      "WORKDIR /src",
      "COPY packages/rust-engine/native ./native",
      "RUN cargo build --release --manifest-path native/Cargo.toml",
      "",
    );
  }
  lines.push(`FROM ${BUN_IMAGE} AS build`, "WORKDIR /repo");
  if (repo) {
    lines.push("COPY . .");
    if (engine) {
      lines.push("COPY --from=engine /src/native/target/release/libforge_engine.so packages/rust-engine/native/target/release/");
    }
    lines.push("RUN bun install --frozen-lockfile", `WORKDIR /repo/${project}`);
  } else {
    lines.push("COPY package.json bun.lock ./", "RUN bun install --frozen-lockfile", "COPY . .");
  }
  lines.push("# One self-contained executable: server, pages, assets, migrations.", "RUN bun run forge build --compile");
  if (sqlite) lines.push("RUN mkdir -p /data");
  lines.push(
    "",
    `FROM ${RUNTIME_IMAGE}`,
    "WORKDIR /app",
    `COPY --from=build /repo/${project === "." ? "" : project + "/"}.forge/build/server /app/server`,
  );
  if (sqlite) {
    lines.push(
      "# SQLite: mount a persistent volume on /data.",
      "COPY --from=build --chown=nonroot:nonroot /data /data",
      'ENV DATABASE_URL="file:/data/app.db"',
      'VOLUME ["/data"]',
    );
  }
  lines.push(
    `ENV NODE_ENV=production PORT=${port}`,
    `EXPOSE ${port}`,
    'ENTRYPOINT ["/app/server"]',
    config.db ? "# Applies pending migrations, then serves." : "",
    config.db ? 'CMD ["start", "--migrate"]' : 'CMD ["start"]',
    "",
  );
  return lines.filter((l, i, all) => l !== "" || all[i - 1] !== "").join("\n");
}

const DOCKERIGNORE = `**/node_modules
**/.forge
**/.vercel
**/generated
**/target
**/*.db
**/*.db-journal
**/.env
**/.env.*
!**/.env.example
.git
`;

function vercelJson(config: ResolvedConfig): string {
  return `${JSON.stringify(
    {
      $schema: "https://openapi.vercel.sh/vercel.json",
      bunVersion: "1.4.x",
      framework: null,
      // .vercel/output (Build Output API) is written by forge build; migrations run at build time.
      buildCommand: config.db ? "bun run forge build && bun run forge db deploy" : "bun run forge build",
    },
    null,
    2,
  )}\n`;
}

async function write(path: string, content: string, out: Out, force: boolean): Promise<boolean> {
  if (existsSync(path) && !force) {
    out.ui.fail(`${path} already exists (--force to overwrite)`);
    return false;
  }
  await Bun.write(path, content);
  out.ui.file("add", relative(process.cwd(), path) || path);
  return true;
}

/** `forge setup docker|vercel`: deployment files for this project. */
export async function setup(root: string, target: string | undefined, force: boolean, out: Out): Promise<number> {
  out.ui.header("setup", target);
  const config = await loadConfig(root);
  if (target === "docker") {
    const repo = workspaceRoot(root);
    const ok = await write(join(root, "Dockerfile"), dockerfile(root, config), out, force);
    const ignore = join(repo ?? root, ".dockerignore");
    if (!existsSync(ignore)) await write(ignore, DOCKERIGNORE, out, false);
    if (repo) out.ui.next([`docker build -f ${relative(repo, join(root, "Dockerfile"))} .   (from the repository root)`]);
    return ok ? 0 : 1;
  }
  if (target === "vercel") {
    if (config.db?.provider === "sqlite") out.ui.warn("SQLite does not persist on Vercel: use postgresql there");
    return (await write(join(root, "vercel.json"), vercelJson(config), out, force)) ? 0 : 1;
  }
  out.ui.fail("Usage: bun forge setup docker|vercel [--force]");
  return 1;
}
