import { Model, model, type FieldDef, type IndexDef, type ModelClass } from "./model.ts";
import type { Provider } from "./schema.ts";

/**
 * Minimal shape of a table description as produced by Better Auth's
 * `getAuthTables()` (core tables, plugins and `additionalFields` included).
 * Kept structural: @forge/models does not depend on Better Auth.
 */
export interface TableField {
  type: string | string[];
  required?: boolean;
  unique?: boolean;
  index?: boolean;
  bigint?: boolean;
  defaultValue?: unknown;
  onUpdate?: unknown;
  fieldName?: string;
  references?: { model: string; field: string; onDelete?: string };
}
export interface TableSchema {
  modelName?: string;
  fields: Record<string, TableField>;
  disableMigrations?: boolean;
}

const ACTIONS: Record<string, "Cascade" | "Restrict" | "NoAction" | "SetNull" | "SetDefault"> = {
  cascade: "Cascade",
  restrict: "Restrict",
  "no action": "NoAction",
  "set null": "SetNull",
  "set default": "SetDefault",
};

const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function named(name: string): ModelClass {
  // A class whose `.name` is the Prisma model name.
  return { [name]: class extends Model {} }[name]! as ModelClass;
}

/**
 * Turns table descriptions into Forge models, mirroring Better Auth's own
 * Prisma generator: capitalized model names, `id String @id` (ids are
 * generated by Better Auth), relation `user` / back relation `sessions`,
 * json and lists stored as text on SQLite. Each model gets `key` =
 * `<prefix>:<table>` so placeholders such as `AuthUser` resolve to it.
 */
export function modelsFromTables(tables: Record<string, TableSchema>, provider: Provider, prefix: string): ModelClass[] {
  const entries = Object.entries(tables).filter(([, t]) => !t.disableMigrations);
  const classes = new Map<string, ModelClass>();
  for (const [key, table] of entries) {
    const cls = named(capitalize(table.modelName ?? key));
    cls.key = `${prefix}:${key}`;
    classes.set(key, cls);
  }

  for (const [key, table] of entries) {
    const cls = classes.get(key)!;
    const shape: Record<string, FieldDef> = { id: model.string() };
    const indexes: IndexDef[] = [];

    for (const [name, f] of Object.entries(table.fields)) {
      const column = f.fieldName ?? name;
      const nullable = f.required === false;

      if (f.references) {
        const target = classes.get(f.references.model);
        if (!target) continue;
        const relation = f.references.model; // Better Auth names the relation field after the table
        const back = `${cls.name.toLowerCase()}${f.unique ? "" : "s"}`;
        const action = ACTIONS[f.references.onDelete ?? "cascade"] ?? "Cascade";
        shape[relation] = (f.unique ? model.oneToOne : model.foreignKey)(target, {
          column,
          nullable,
          onDelete: action,
          related: back,
        });
        if (f.index && !f.unique) indexes.push(model.index([relation]));
        continue;
      }

      const common = {
        nullable,
        ...(f.unique ? { unique: true } : {}),
        ...(column !== name ? {} : {}),
      };
      const lit = f.defaultValue;
      const literal = typeof lit === "string" || typeof lit === "number" || typeof lit === "boolean" ? lit : undefined;
      let def: FieldDef;
      const t = f.type;
      if (Array.isArray(t) || t === "string") {
        def = model.string({ ...common, ...(literal !== undefined ? { default: String(literal) } : {}) });
      } else if (t === "number") {
        def = (f.bigint ? model.bigint : model.int)({ ...common, ...(typeof literal === "number" ? { default: literal } : {}) });
      } else if (t === "boolean") {
        def = model.boolean({ ...common, ...(typeof literal === "boolean" ? { default: literal } : {}) });
      } else if (t === "date") {
        def = model.dateTime({
          ...common,
          ...(name === "createdAt" ? { default: model.now() } : {}),
          ...(name === "updatedAt" && f.onUpdate ? { updatedAt: true } : {}),
        });
      } else if (t === "json") {
        def = provider === "sqlite" ? model.string(common) : model.json(common);
      } else if (t === "string[]" || t === "number[]") {
        def =
          provider === "sqlite"
            ? model.string(common)
            : { kind: "scalar", type: t === "string[]" ? "String" : "Int", options: { list: true } };
      } else {
        def = model.string(common);
      }
      shape[column] = def;
      if (f.index && !f.unique) indexes.push(model.index([column]));
    }

    cls.model = shape;
    cls.indexes = indexes;
  }
  return [...classes.values()];
}
