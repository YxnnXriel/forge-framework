import { ForgeError } from "@forge/core";
import type { DefaultFn, EnumField, FieldDef, IndexDef, ModelClass, RelationField, ScalarField } from "./model.ts";

export type Provider = "postgresql" | "sqlite";

export class ForgeModelError extends ForgeError {
  override readonly name = "ForgeModelError";
  constructor(message: string) {
    super("FORGE_MODEL_INVALID", message);
  }
}

const IDENT = /^[A-Za-z][A-Za-z0-9_]*$/;
const TIMESTAMP_FIELDS = ["createdAt", "updatedAt", "deletedAt"] as const;

const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const upperFirst = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** Small English pluralization for generated back-relation names. */
export function plural(word: string): string {
  if (/[^aeiou]y$/i.test(word)) return word.slice(0, -1) + "ies";
  if (/(s|x|z|ch|sh)$/i.test(word)) return word + "es";
  return word + "s";
}

interface Line {
  name: string;
  type: string;
  attrs: string[];
}

interface ModelIR {
  name: string;
  cls: ModelClass;
  lines: Line[];
  /** Fields generated by relations declared on other models (sorted at the end). */
  back: Line[];
  block: string[];
}

function renderDefault(value: unknown, field: string, model: string): string {
  if (typeof value === "object" && value !== null && (value as DefaultFn).kind === "fn") {
    const f = (value as DefaultFn).fn;
    return f === "uuid7" ? "uuid(7)" : `${f}()`;
  }
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "bigint" || typeof value === "boolean") return String(value);
  if (value instanceof Date) return JSON.stringify(value.toISOString());
  throw new ForgeModelError(`${model}.${field}: unsupported default value ${String(value)}`);
}

function scalarLine(name: string, f: ScalarField, provider: Provider, model: string): Line {
  const o = f.options;
  const attrs: string[] = [];
  if (o.default !== undefined) attrs.push(`@default(${renderDefault(o.default, name, model)})`);
  if (o.updatedAt) attrs.push("@updatedAt");
  if (o.unique) attrs.push("@unique");
  if (provider === "postgresql") {
    if (o.uuid) attrs.push("@db.Uuid");
    else if (o.text) attrs.push("@db.Text");
    else if (o.maxLength !== undefined) attrs.push(`@db.VarChar(${o.maxLength})`);
    if (f.type === "Decimal" && o.precision !== undefined) attrs.push(`@db.Decimal(${o.precision}, ${o.scale ?? 0})`);
  }
  if (o.column) attrs.push(`@map(${JSON.stringify(o.column)})`);
  return { name, type: f.type + (o.list ? "[]" : o.nullable ? "?" : ""), attrs };
}

/** Prisma type and native attribute of a model's primary key, to type foreign keys. */
function idOf(ir: ModelIR): Line {
  const id = ir.lines.find((l) => l.attrs.includes("@id"))!;
  return id;
}

export interface GeneratedSchema {
  /** Content of `forge.generated.prisma`. */
  content: string;
  /** Model names, in output order. */
  models: string[];
  /** Hash of the content, written in its header (sync check). */
  hash: string;
}

/**
 * Turns Forge models into Prisma models. Pure: same input, same output.
 * Relations are named `<Model>_<field>`, which keeps several relations
 * between the same two models unambiguous.
 */
export function generateSchema(classes: readonly ModelClass[], provider: Provider): GeneratedSchema {
  const byClass = new Map<ModelClass, ModelIR>();
  const names = new Set<string>();

  for (const cls of classes) {
    const name = cls.name;
    if (!IDENT.test(name) || name[0] !== name[0]!.toUpperCase()) {
      throw new ForgeModelError(`Model class "${name}" must be PascalCase (it becomes the Prisma model name)`);
    }
    if (names.has(name)) throw new ForgeModelError(`Two models are named "${name}"`);
    names.add(name);
    byClass.set(cls, { name, cls, lines: [], back: [], block: [] });
  }

  const byKey = new Map<string, ModelIR>();
  for (const ir of byClass.values()) if (ir.cls.key) byKey.set(ir.cls.key, ir);

  const enums: string[] = [];
  const enumNames = new Set<string>();

  // 1. Own fields: id, scalars, enums, timestamps.
  for (const ir of byClass.values()) {
    const shape = ir.cls.model ?? {};
    for (const field of Object.keys(shape)) {
      if (!IDENT.test(field)) throw new ForgeModelError(`${ir.name}.${field}: invalid field name`);
    }
    const idDef = shape.id;
    if (idDef) {
      if (idDef.kind !== "scalar") throw new ForgeModelError(`${ir.name}.id must be a scalar field (model.uuid(), model.autoIncrement()...)`);
      const line = scalarLine("id", idDef, provider, ir.name);
      if (line.type.endsWith("?")) throw new ForgeModelError(`${ir.name}.id cannot be nullable`);
      line.attrs = ["@id", ...line.attrs.filter((a) => a !== "@unique")];
      ir.lines.push(line);
    } else {
      ir.lines.push({
        name: "id",
        type: "String",
        attrs: ["@id", "@default(uuid())", ...(provider === "postgresql" ? ["@db.Uuid"] : [])],
      });
    }

    for (const [field, def] of Object.entries(shape)) {
      if (field === "id") continue;
      if (ir.cls.timestamps && (TIMESTAMP_FIELDS as readonly string[]).includes(field)) {
        throw new ForgeModelError(`${ir.name}.${field} is added by \`static timestamps = true\`; remove it or disable timestamps`);
      }
      if (def.kind === "scalar") ir.lines.push(scalarLine(field, def, provider, ir.name));
      else if (def.kind === "enum") ir.lines.push(enumLine(ir.name, field, def));
    }

    if (ir.cls.timestamps) {
      ir.lines.push({ name: "createdAt", type: "DateTime", attrs: ["@default(now())"] });
      ir.lines.push({ name: "updatedAt", type: "DateTime", attrs: ["@updatedAt"] });
      ir.lines.push({ name: "deletedAt", type: "DateTime?", attrs: [] });
    }
  }

  function enumLine(model: string, field: string, def: EnumField): Line {
    const enumName = def.options.name ?? `${model}${upperFirst(field)}`;
    if (def.values.length === 0) throw new ForgeModelError(`${model}.${field}: an enum needs at least one value`);
    for (const v of def.values) if (!IDENT.test(v)) throw new ForgeModelError(`${model}.${field}: invalid enum value "${v}"`);
    if (!enumNames.has(enumName)) {
      enumNames.add(enumName);
      enums.push(`enum ${enumName} {\n${def.values.map((v) => `  ${v}`).join("\n")}\n}`);
    }
    const attrs: string[] = [];
    if (def.options.default !== undefined) {
      if (!def.values.includes(def.options.default as string)) {
        throw new ForgeModelError(`${model}.${field}: default "${String(def.options.default)}" is not one of the enum values`);
      }
      attrs.push(`@default(${String(def.options.default)})`);
    }
    if (def.options.unique) attrs.push("@unique");
    if (def.options.column) attrs.push(`@map(${JSON.stringify(def.options.column)})`);
    return { name: field, type: enumName + (def.options.nullable ? "?" : ""), attrs };
  }

  // 2. Relations, with the generated field on the other side.
  const has = (ir: ModelIR, field: string) => ir.lines.some((l) => l.name === field) || ir.back.some((l) => l.name === field);
  const addBack = (target: ModelIR, field: string, line: Line, origin: string) => {
    if (has(target, field)) {
      throw new ForgeModelError(
        `${origin} would add "${field}" on ${target.name}, which already has that field. Set \`related: "<name>"\` on ${origin}.`,
      );
    }
    target.back.push(line);
  };

  for (const ir of byClass.values()) {
    for (const [field, def] of Object.entries(ir.cls.model ?? {})) {
      if (def.kind !== "relation") continue;
      const origin = `${ir.name}.${field}`;
      let targetCls: ModelClass | undefined;
      try {
        targetCls = def.target() as unknown as ModelClass;
      } catch (e) {
        throw new ForgeModelError(`${origin}: could not resolve the target model (${(e as Error).message})`);
      }
      const target = targetCls && (byClass.get(targetCls) ?? (targetCls.key ? byKey.get(targetCls.key) : undefined));
      if (!target) {
        throw new ForgeModelError(
          `${origin} references ${targetCls?.name ?? "an unknown model"}, which is not exported from any src/apps/*/models.ts`,
        );
      }
      const relName = JSON.stringify(`${ir.name}_${field}`);
      const rel = def as RelationField;

      if (rel.relation === "manyToMany") {
        ir.lines.push({ name: field, type: `${target.name}[]`, attrs: [`@relation(${relName})`] });
        const back = rel.options.related ?? plural(lowerFirst(ir.name));
        addBack(target, back, { name: back, type: `${ir.name}[]`, attrs: [`@relation(${relName})`] }, origin);
        continue;
      }

      const fk = rel.options.column ?? `${field}Id`;
      const targetId = idOf(target);
      const fkAttrs = targetId.attrs.filter((a) => a.startsWith("@db."));
      if (rel.relation === "oneToOne") fkAttrs.unshift("@unique");
      const nullable = rel.options.nullable === true;
      if (has(ir, fk)) throw new ForgeModelError(`${origin}: foreign key column "${fk}" clashes with an existing field`);
      ir.lines.push({ name: fk, type: targetId.type + (nullable ? "?" : ""), attrs: fkAttrs });

      const args = [relName, `fields: [${fk}]`, `references: [id]`];
      if (rel.options.onDelete) args.push(`onDelete: ${rel.options.onDelete}`);
      if (rel.options.onUpdate) args.push(`onUpdate: ${rel.options.onUpdate}`);
      ir.lines.push({ name: field, type: target.name + (nullable ? "?" : ""), attrs: [`@relation(${args.join(", ")})`] });

      const back =
        rel.options.related ?? (rel.relation === "oneToOne" ? lowerFirst(ir.name) : plural(lowerFirst(ir.name)));
      const backType = rel.relation === "oneToOne" ? `${ir.name}?` : `${ir.name}[]`;
      addBack(target, back, { name: back, type: backType, attrs: [`@relation(${relName})`] }, origin);
    }
  }

  // Generated back relations go last, sorted: output does not depend on discovery order.
  for (const ir of byClass.values()) ir.lines.push(...ir.back.sort((a, b) => a.name.localeCompare(b.name)));

  // 3. Indexes, table names.
  for (const ir of byClass.values()) {
    for (const idx of (ir.cls.indexes ?? []) as readonly IndexDef[]) {
      const cols = idx.fields.map((f) => {
        const def = ir.cls.model?.[f];
        const column = def?.kind === "relation" && def.relation !== "manyToMany" ? (def.options.column ?? `${f}Id`) : f;
        const line = ir.lines.find((l) => l.name === column);
        if (!line || line.type.endsWith("[]")) {
          throw new ForgeModelError(`${ir.name}: index on unknown or list field "${f}"`);
        }
        return column;
      });
      const name = idx.name ? `, map: ${JSON.stringify(idx.name)}` : "";
      ir.block.push(`@@${idx.kind === "unique" ? "unique" : "index"}([${cols.join(", ")}]${name})`);
    }
    if (ir.cls.table) ir.block.push(`@@map(${JSON.stringify(ir.cls.table)})`);
  }

  const models = [...byClass.values()].sort((a, b) => a.name.localeCompare(b.name));
  const body = [
    ...enums.sort(),
    ...models.map((ir) => {
      const w1 = Math.max(...ir.lines.map((l) => l.name.length));
      const w2 = Math.max(...ir.lines.map((l) => l.type.length));
      const rows = ir.lines.map((l) =>
        `  ${l.name.padEnd(w1)} ${l.attrs.length ? l.type.padEnd(w2) + " " + l.attrs.join(" ") : l.type}`.trimEnd(),
      );
      const block = ir.block.length ? `\n\n${ir.block.map((b) => `  ${b}`).join("\n")}` : "";
      return `model ${ir.name} {\n${rows.join("\n")}${block}\n}`;
    }),
  ].join("\n\n");

  const hash = new Bun.CryptoHasher("sha256").update(`${provider}\n${body}`).digest("hex").slice(0, 16);
  const content = `// Generated by Forge from src/apps/*/models.ts. Do not edit: run \`forge db generate\`.
// forge-hash: ${hash}

${body}
`;
  return { content, models: models.map((m) => m.name), hash };
}

/** Reads the hash written in a generated schema header. */
export function readSchemaHash(content: string): string | null {
  return /^\/\/ forge-hash: ([0-9a-f]+)$/m.exec(content)?.[1] ?? null;
}
